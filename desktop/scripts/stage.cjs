const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const destination = process.argv[2];
if (!destination || !path.isAbsolute(destination)) throw new Error('Pass an absolute staging directory');
fs.mkdirSync(destination, { recursive: true });
const electronDirectory = path.dirname(require('electron'));
fs.cpSync(electronDirectory, destination, { recursive: true });
fs.renameSync(path.join(destination, 'electron.exe'), path.join(destination, 'HuifaVideoDownloader.exe'));
const application = path.join(destination, 'resources/app');
fs.mkdirSync(application, { recursive: true });
fs.cpSync(path.join(root, 'desktop/dist'), path.join(application, 'dist'), { recursive: true });
fs.cpSync(path.join(root, 'desktop/src/styles.css'), path.join(application, 'src/styles.css'));
fs.copyFileSync(path.join(root, 'desktop/index.html'), path.join(application, 'index.html'));
fs.writeFileSync(path.join(application, 'package.json'), JSON.stringify({ name: 'huifa-desktop', version: '0.0.0', main: 'dist/main.js' }));
fs.cpSync(path.join(root, 'assets'), path.join(destination, 'assets'), { recursive: true });
