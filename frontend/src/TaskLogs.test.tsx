import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { StrictMode } from 'react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { TaskLogsDialog } from './TaskLogs';
import { makeTask } from './test-fixtures';
import { translate } from './i18n';
import type { TaskLogs } from './types';

const command = vi.hoisted(() => vi.fn());
vi.mock('./transport', () => ({ host: { command } }));
const t = (_zh: string, en: string) => en;
const raw = '[call] yt-dlp --cookies C:\\private\\cookies.txt https://example.test/?token=secret\n[stdout] {"formats":[{"url":"https://media.test/?signature=raw"}]}\n[stderr] WARNING: fixture diagnostic\n[progress] 52%\r[progress] 53%\r\n';
const page = (text = raw, start = 0, total = new TextEncoder().encode(text).length, legacy = false): TaskLogs => ({ text, start, end: start + new TextEncoder().encode(text).length, total, hasMore: start > 0, raw: true, legacy });
beforeEach(() => { command.mockReset(); });
afterEach(() => { vi.useRealTimers(); });

describe('raw task logs', () => {
  it('loads exact raw output once under StrictMode, retains frozen filters, and copies the full file rather than only its tail', async () => {
    const full = 'x'.repeat(262144) + raw;
    const tail = full.slice(-65536);
    command.mockImplementation(async (_name, args) => args.offset === undefined ? page(tail, full.length - tail.length, full.length) : page(full.slice(args.offset, args.offset + args.limit), args.offset, full.length));
    const writeText = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } });
    const close = vi.fn();
    render(<StrictMode><TaskLogsDialog task={{ ...makeTask('task-a', 'Live fixture'), status: 'failed', stage: 'probing', options: { liveFilter: 'videos', dateAfter: '2026-10-01', durationMax: 300 } }} t={t} close={close} /></StrictMode>);
    const dialog = within(screen.getByRole('dialog', { name: 'Task logs' }));
    await dialog.findByLabelText('Task log entries');
    expect(command).toHaveBeenCalledOnce();
    expect(command).toHaveBeenCalledWith('tasks.logs', { id: 'task-a', limit: 65536 });
    expect(dialog.getByLabelText('Task log entries').textContent).toBe(tail);
    const filters = within(dialog.getByRole('region', { name: 'Task filters' }));
    expect(filters.getByText('Non-live videos')).toBeTruthy(); expect(filters.getByText('2026-10-01')).toBeTruthy(); expect(filters.getByText('300')).toBeTruthy();
    fireEvent.click(dialog.getByRole('button', { name: 'Copy full log' }));
    await waitFor(() => expect(writeText).toHaveBeenCalledWith(full));
    expect(command.mock.calls.slice(1).map(([, args]) => args.offset)).toEqual([0, 262144]);
    expect(await dialog.findByRole('button', { name: 'Copied' })).toBeTruthy();
    fireEvent.click(dialog.getByRole('button', { name: 'Close' }));
    expect(close).toHaveBeenCalledOnce();
  });
  it('pages both directions and returns to the latest logs without claiming legacy summaries are raw history', async () => {
    command.mockResolvedValueOnce(page('tail', 8, 12)).mockResolvedValueOnce(page('middle', 2, 12)).mockResolvedValueOnce(page('tail', 8, 12)).mockResolvedValueOnce(page('middle', 2, 12)).mockResolvedValueOnce(page('tail', 8, 12));
    render(<TaskLogsDialog task={{ ...makeTask('task-b'), status: 'failed' }} t={t} close={() => {}} />);
    await screen.findByLabelText('Task log entries');
    fireEvent.click(screen.getByRole('button', { name: 'Older logs' }));
    await waitFor(() => expect(screen.getByLabelText('Task log entries').textContent).toBe('middle'));
    expect(command).toHaveBeenLastCalledWith('tasks.logs', { id: 'task-b', limit: 65536, before: 8 });
    fireEvent.click(screen.getByRole('button', { name: 'Newer logs' }));
    await waitFor(() => expect(screen.getByLabelText('Task log entries').textContent).toBe('tail'));
    expect(command).toHaveBeenLastCalledWith('tasks.logs', { id: 'task-b', limit: 65536, offset: 8 });
    fireEvent.click(screen.getByRole('button', { name: 'Older logs' }));
    await waitFor(() => expect(command).toHaveBeenCalledTimes(4));
    await waitFor(() => expect(screen.getByLabelText('Task log entries').textContent).toBe('middle'));
    fireEvent.click(screen.getByRole('button', { name: 'Latest logs' }));
    await waitFor(() => expect(screen.getByLabelText('Task log entries').textContent).toBe('tail'));
    expect(command).toHaveBeenLastCalledWith('tasks.logs', { id: 'task-b', limit: 65536 });
  });
  it('refreshes active logs every two seconds without overlapping requests and stops after the final refresh and close', async () => {
    vi.useFakeTimers();
    let finish!: (value: TaskLogs) => void;
    command.mockResolvedValueOnce(page('first')).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; })).mockResolvedValue(page('final'));
    const task = makeTask('task-c');
    const view = render(<TaskLogsDialog task={task} t={t} close={() => {}} />);
    await act(async () => {});
    expect(screen.getByLabelText('Task log entries').textContent).toBe('first');
    await act(async () => { await vi.advanceTimersByTimeAsync(2000); });
    expect(command).toHaveBeenCalledTimes(2);
    await act(async () => { await vi.advanceTimersByTimeAsync(6000); });
    expect(command).toHaveBeenCalledTimes(2);
    await act(async () => finish(page('second')));
    expect(screen.getByLabelText('Task log entries').textContent).toBe('second');
    view.rerender(<TaskLogsDialog task={{ ...task, status: 'cancelled' }} t={t} close={() => {}} />);
    await act(async () => {});
    expect(command).toHaveBeenCalledTimes(3);
    await act(async () => { await vi.advanceTimersByTimeAsync(6000); });
    expect(command).toHaveBeenCalledTimes(3);
    view.unmount();
    await act(async () => { await vi.advanceTimersByTimeAsync(6000); });
    expect(command).toHaveBeenCalledTimes(3);
    const running = render(<TaskLogsDialog task={task} t={t} close={() => {}} />);
    await act(async () => {});
    expect(command).toHaveBeenCalledTimes(4);
    running.unmount();
    await act(async () => { await vi.advanceTimersByTimeAsync(6000); });
    expect(command).toHaveBeenCalledTimes(4);
  });
  it('leaves older pages in place while the available byte count refreshes', async () => {
    vi.useFakeTimers();
    command.mockResolvedValueOnce(page('tail', 8, 12)).mockResolvedValueOnce(page('head', 0, 12)).mockResolvedValueOnce(page('new tail', 8, 16));
    render(<TaskLogsDialog task={makeTask('task-d')} t={t} close={() => {}} />);
    await act(async () => {});
    fireEvent.click(screen.getByRole('button', { name: 'Older logs' }));
    await act(async () => {});
    await act(async () => { await vi.advanceTimersByTimeAsync(2000); });
    expect(screen.getByLabelText('Task log entries').textContent).toBe('head');
    expect(screen.getByText('Bytes 0–4 / 16')).toBeTruthy();
    expect((screen.getByRole('button', { name: 'Latest logs' }) as HTMLButtonElement).disabled).toBe(false);
  });
  it('cancels a full-copy operation without copying a partial file or continuing after close', async () => {
    let finish!: (value: TaskLogs) => void;
    const writeText = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } });
    command.mockResolvedValueOnce(page('tail', 524284, 524288)).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
    const view = render(<TaskLogsDialog task={{ ...makeTask('task-e'), status: 'failed' }} t={t} close={() => {}} />);
    await screen.findByLabelText('Task log entries');
    fireEvent.click(screen.getByRole('button', { name: 'Copy full log' }));
    await waitFor(() => expect(command).toHaveBeenCalledTimes(2));
    fireEvent.click(screen.getByRole('button', { name: 'Cancel copying' }));
    view.unmount();
    await act(async () => finish(page('x'.repeat(262144), 0, 524288)));
    expect(command).toHaveBeenCalledTimes(2);
    expect(writeText).not.toHaveBeenCalled();
  });
  it('copies a short final chunk within the initial file boundary when new bytes arrive during copying', async () => {
    const writeText = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } });
    command.mockResolvedValueOnce(page('ab')).mockResolvedValueOnce(page('abNE', 0, 6));
    render(<TaskLogsDialog task={{ ...makeTask('task-short'), status: 'failed' }} t={t} close={() => {}} />);
    await screen.findByLabelText('Task log entries');
    fireEvent.click(screen.getByRole('button', { name: 'Copy full log' }));
    await waitFor(() => expect(writeText).toHaveBeenCalledWith('ab'));
    expect(command).toHaveBeenLastCalledWith('tasks.logs', { id: 'task-short', offset: 0, limit: 4 });
  });
  it('keeps an empty legacy history honest and can retry an error', async () => {
    command.mockRejectedValueOnce(new Error('Task log fixture unavailable')).mockResolvedValueOnce(page('', 0, 0, true));
    render(<TaskLogsDialog task={{ ...makeTask('task-f'), status: 'failed' }} t={t} close={() => {}} />);
    expect((await screen.findByRole('alert')).textContent).toBe('Task log fixture unavailable');
    fireEvent.click(screen.getByRole('button', { name: 'Refresh' }));
    expect(await screen.findByText('No logs have been recorded for this task.')).toBeTruthy();
    expect(screen.getByText(/Raw output was not recorded for this run/)).toBeTruthy();
    expect(screen.queryByLabelText('Task log entries')).toBeNull();
    expect(screen.queryByRole('alert')).toBeNull();
  });
  it('shows Chinese text and an actionable error when clipboard access is unavailable', async () => {
    command.mockResolvedValue(page());
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined });
    render(<TaskLogsDialog task={{ ...makeTask('task-g'), status: 'failed' }} t={(zh, en) => translate('zh-CN', zh, en)} close={() => {}} />);
    const dialog = within(screen.getByRole('dialog', { name: '任务日志' }));
    await dialog.findByLabelText('任务日志内容');
    fireEvent.click(dialog.getByRole('button', { name: '复制完整日志' }));
    expect((await dialog.findByRole('alert')).textContent).toBe('无法复制，请在日志中选中文本后手动复制。');
  });
});
